import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Image SEO + Merchant image audit (Sprint 8). Read-only: it never rewrites, recompresses or renames an original —
 * the 445 SHA-256 hashes are the contract. Two layers:
 *  - analyzeImages(): pure, DB facts only (dimensions, MIME, size, alt per language, usage, duplicates, filename)
 *  - verifyFiles(): reads public/upload + data/source-media, recomputes SHA-256 and sniffs the real format
 *
 * Merchant thresholds (Google Merchant Center image requirements, checked 2026-10): non-apparel minimum is 100×100
 * today; from 31 Jan 2027 the KORNNE plan treats 500×500 as the minimum (spec); 1500×1500 recommended for zoom.
 * Max 16 MB / 64 MP. Accepted formats: JPEG, PNG, GIF (static), BMP, TIFF, WebP. Watermarks, promotional overlays and
 * logos as main image are not allowed — they cannot be detected automatically, so filename/aspect HEURISTICS only
 * raise "manual review" items (never a verdict).
 */
export const MERCHANT_MIN_NOW = 100;
export const MERCHANT_MIN_2027 = 500;
export const MERCHANT_RECOMMENDED = 1500;
export const MERCHANT_MIN_DATE = "2027-01-31";
export const MERCHANT_MAX_BYTES = 16 * 1024 * 1024;
const MERCHANT_MIME = new Set(["image/jpeg", "image/png", "image/gif", "image/bmp", "image/tiff", "image/webp"]);

export type ImageRow = {
  id: string;
  publicPath: string;
  storageKey: string;
  sha256: string;
  mime: string;
  bytes: number;
  width: number | null;
  height: number | null;
  origin: string;
  alts: { locale: string; alt: string; autoGenerated: boolean }[];
  usages: { productId: string; productRef: string; productTitle: string; public: boolean; isMain: boolean }[];
  bannerCount: number;
};

export type ImageIssue = { code: string; severity: "error" | "warning" | "info"; message: string; fix: string };
export type ImageItem = { id: string; publicPath: string; fileName: string; width: number | null; height: number | null; mime: string; bytes: number; sha256: string; isMainOfPublic: boolean; usedBy: ImageRow["usages"]; duplicates: string[]; altLocales: string[]; merchant: "OK" | "BELOW_2027" | "BELOW_NOW" | "UNKNOWN" | "NOT_USED"; issues: ImageIssue[] };

export type BrokenImage = { url: string; usage: string; status: string };

const I = (code: string, severity: ImageIssue["severity"], message: string, fix: string): ImageIssue => ({ code, severity, message, fix });
const SUSPECT_NAME = /(whatsapp|img[-_]\d{6,}|screenshot|ekran[ _-]?g[öo]r|logo|banner|filigran|watermark|kampanya|indirim|\(\d+ x \d+)/i;

export function analyzeImages(rows: ImageRow[]) {
  const bySha = new Map<string, string[]>();
  for (const r of rows) bySha.set(r.sha256, [...(bySha.get(r.sha256) ?? []), r.publicPath]);
  const items = rows.map((r): ImageItem => {
    const issues: ImageIssue[] = [];
    const fileName = decodeURIComponent(r.publicPath.split("/").pop() ?? r.publicPath);
    const isMain = r.usages.some((u) => u.public && u.isMain);
    const usedPublic = r.usages.some((u) => u.public);
    const short = r.width && r.height ? Math.min(r.width, r.height) : null;
    let merchant: ImageItem["merchant"] = !usedPublic ? "NOT_USED" : short === null ? "UNKNOWN" : short < MERCHANT_MIN_NOW ? "BELOW_NOW" : short < MERCHANT_MIN_2027 ? "BELOW_2027" : "OK";
    if (short === null) issues.push(I("dims-unknown", "warning", "Boyut bilinmiyor", "Dosyayı yeniden ölçün (verifyFiles)"));
    else if (usedPublic && short < MERCHANT_MIN_2027) issues.push(I(isMain ? "merchant-main-below-500" : "below-500", isMain ? "error" : "warning", `${r.width}×${r.height} — 500×500 altı (Merchant asgari şartı ${MERCHANT_MIN_DATE} itibarıyla)`, "Müşteriden aynı ürünün ≥1500 px orijinal fotoğrafını isteyin; mevcut dosya büyütülmez"));
    else if (isMain && short < MERCHANT_RECOMMENDED) issues.push(I("below-recommended", "info", `${r.width}×${r.height} — önerilen 1500 px altı (yakınlaştırma)`, "Varsa daha yüksek çözünürlüklü orijinal"));
    if (!MERCHANT_MIME.has(r.mime)) issues.push(I("mime", isMain ? "error" : "warning", `Biçim ${r.mime} Merchant tarafından kabul edilmiyor`, "Orijinal korunur; Merchant için JPEG/PNG/WebP türev üretimi müşteri onayıyla"));
    const extMime = ({ jpg: "image/jpeg", jpeg: "image/jpeg", png: "image/png", gif: "image/gif", webp: "image/webp" } as Record<string, string>)[fileName.split(".").pop()?.toLowerCase() ?? ""];
    if (extMime && extMime !== r.mime) issues.push(I("ext-mismatch", usedPublic ? "warning" : "info", `Uzantı ${extMime} bildiriyor ama dosya ${r.mime} — sunucu yanlış Content-Type gönderir`, "Eski URL korunduğu için dosya değiştirilmez; yeni kullanımda doğru uzantılı türev"));
    if (r.bytes > MERCHANT_MAX_BYTES) issues.push(I("too-large", "error", `${(r.bytes / 1048576).toFixed(1)} MB > 16 MB`, "Merchant türevi gerekli"));
    else if (r.bytes > 1_500_000) issues.push(I("heavy", "info", `${(r.bytes / 1048576).toFixed(1)} MB — sayfa ağırlığı`, "Site next/image ile AVIF/WebP türev sunar; orijinal korunur"));
    if (r.width && r.height && usedPublic && (r.width / r.height > 3 || r.height / r.width > 3)) issues.push(I("aspect", isMain ? "error" : "warning", `En-boy oranı ${(r.width / r.height).toFixed(2)} — ürün görseli için uygun değil (banner?)`, "Ürün fotoğrafı ana görsel olmalı"));
    const altLocales = r.alts.filter((a) => a.alt.trim() && !a.autoGenerated).map((a) => a.locale);
    if (usedPublic && !altLocales.includes("tr")) issues.push(I("alt-missing", "warning", r.alts.some((a) => a.locale === "tr") ? "Türkçe alt metin otomatik (ürün adından) — editör onayı yok" : "Türkçe alt metin yok", "Admin › Görsel SEO'dan görseli tarif eden alt metin yazın"));
    if (usedPublic && SUSPECT_NAME.test(fileName)) issues.push(I("filename-suspect", "warning", `Dosya adı "${fileName.slice(0, 50)}" — WhatsApp/ekran görüntüsü/logo/afiş olabilir`, "Manuel inceleme: filigran, yazı veya logo var mı? (otomatik karar verilmez)"));
    else if (usedPublic && !/[a-z]{3,}/i.test(fileName.replace(/\.[a-z]+$/i, "").replace(/^\d+-[0-9a-f]+$/i, ""))) issues.push(I("filename-meaningless", "info", "Anlamsız dosya adı (Google Görseller sinyali zayıf)", "URL'ler korunur (eski bağlantılar); yeni yüklemelerde açıklayıcı ad"));
    const dups = (bySha.get(r.sha256) ?? []).filter((p) => p !== r.publicPath);
    if (dups.length) issues.push(I("duplicate", "info", `Bayt-bayt aynı ${dups.length} kopya`, "Tek kopya yeter; eski URL'ler yönlendirme/aynı dosya ile korunur"));
    if (!r.usages.length && !r.bannerCount) issues.push(I("orphan", "info", "Hiçbir ürün/afişte kullanılmıyor", "Arşiv: silinmez (445 orijinal korunur)"));
    if (merchant === "OK" && !isMain) merchant = usedPublic ? "OK" : "NOT_USED";
    return { id: r.id, publicPath: r.publicPath, fileName, width: r.width, height: r.height, mime: r.mime, bytes: r.bytes, sha256: r.sha256, isMainOfPublic: isMain, usedBy: r.usages, duplicates: dups, altLocales, merchant, issues };
  });
  const main = items.filter((i) => i.isMainOfPublic);
  const summary = {
    total: items.length,
    usedByPublicProducts: items.filter((i) => i.usedBy.some((u) => u.public)).length,
    mainImages: main.length,
    mainBelow500: main.filter((i) => i.merchant === "BELOW_2027" || i.merchant === "BELOW_NOW").length,
    mainBelow1500: main.filter((i) => i.width && i.height && Math.min(i.width, i.height) < MERCHANT_RECOMMENDED).length,
    allBelow500: items.filter((i) => i.width && i.height && Math.min(i.width, i.height) < MERCHANT_MIN_2027).length,
    publicBelow500: items.filter((i) => i.usedBy.some((u) => u.public) && i.width && i.height && Math.min(i.width, i.height) < MERCHANT_MIN_2027).length,
    altMissingTr: items.filter((i) => i.issues.some((x) => x.code === "alt-missing")).length,
    duplicateGroups: new Set(items.filter((i) => i.duplicates.length).map((i) => i.sha256)).size,
    suspectNames: items.filter((i) => i.issues.some((x) => x.code === "filename-suspect")).length,
    orphans: items.filter((i) => i.issues.some((x) => x.code === "orphan")).length,
    nonMerchantMime: items.filter((i) => i.issues.some((x) => x.code === "mime")).length,
  };
  return { items, summary };
}

/** Real file format from magic bytes (never trusts the extension or the DB MIME). */
export function sniffMime(buf: Buffer): string | null {
  if (buf.length < 12) return null;
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "image/jpeg";
  if (buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return "image/png";
  if (buf.subarray(0, 6).toString("ascii") === "GIF87a" || buf.subarray(0, 6).toString("ascii") === "GIF89a") return "image/gif";
  if (buf.subarray(0, 4).toString("ascii") === "RIFF" && buf.subarray(8, 12).toString("ascii") === "WEBP") return "image/webp";
  if (buf[0] === 0x42 && buf[1] === 0x4d) return "image/bmp";
  if ((buf[0] === 0x49 && buf[1] === 0x49 && buf[2] === 0x2a) || (buf[0] === 0x4d && buf[1] === 0x4d && buf[3] === 0x2a)) return "image/tiff";
  if (buf.subarray(4, 12).toString("ascii").startsWith("ftypavif")) return "image/avif";
  if (buf.subarray(0, 256).toString("utf8").trimStart().startsWith("<")) return "image/svg+xml";
  return null;
}

export type FileCheck = { checked: number; originalMismatch: string[]; servedMismatch: string[]; missing: string[]; mimeMismatch: { path: string; db: string; real: string | null }[] };

/** Recomputes SHA-256 of the original and the served copy and sniffs the format. Read-only. */
export function verifyFiles(rows: Pick<ImageRow, "publicPath" | "storageKey" | "sha256" | "mime">[], root = process.cwd()): FileCheck {
  const out: FileCheck = { checked: 0, originalMismatch: [], servedMismatch: [], missing: [], mimeMismatch: [] };
  for (const r of rows) {
    const orig = join(root, "data/source-media", r.storageKey);
    const served = join(root, "public", r.publicPath);
    if (!existsSync(served)) {
      out.missing.push(r.publicPath);
      continue;
    }
    const buf = readFileSync(served);
    out.checked++;
    if (createHash("sha256").update(buf).digest("hex") !== r.sha256) out.servedMismatch.push(r.publicPath);
    if (existsSync(orig) && createHash("sha256").update(readFileSync(orig)).digest("hex") !== r.sha256) out.originalMismatch.push(r.storageKey);
    const real = sniffMime(buf);
    if (real !== r.mime && !(r.mime === "image/jpg" && real === "image/jpeg")) out.mimeMismatch.push({ path: r.publicPath, db: r.mime, real });
  }
  return out;
}

/** The legacy images that were already 404 on kornne.com (docs/audit/media-inventory.csv) — reported, never faked. */
export function brokenFromInventory(csv: string): BrokenImage[] {
  const lines = csv.trim().split(/\r?\n/);
  const parse = (l: string) => {
    const o: string[] = [];
    let c = "";
    let q = false;
    for (const ch of l) {
      if (ch === '"') q = !q;
      else if (ch === "," && !q) {
        o.push(c);
        c = "";
      } else c += ch;
    }
    o.push(c);
    return o;
  };
  const head = parse(lines[0] ?? "");
  const ix = (k: string) => head.indexOf(k);
  return lines
    .slice(1)
    .map(parse)
    .filter((r) => r[ix("http_status")] !== "200")
    .map((r) => ({ url: r[ix("url")] ?? "", usage: r[ix("usages")] ?? "", status: r[ix("http_status")] ?? "" }));
}

/** Loads the audit rows from the database (read-only). */
export async function loadImageRows(db: import("@prisma/client").PrismaClient): Promise<ImageRow[]> {
  const media = await db.mediaAsset.findMany({
    orderBy: { publicPath: "asc" },
    select: {
      id: true, publicPath: true, storageKey: true, sha256: true, mime: true, bytes: true, width: true, height: true, origin: true,
      translations: { select: { locale: true, alt: true, autoGenerated: true } },
      products: { select: { sortOrder: true, isPrimary: true, product: { select: { id: true, sourceKey: true, status: true, needsReview: true, translations: { where: { locale: "tr" }, select: { title: true } }, media: { select: { mediaId: true, sortOrder: true, isPrimary: true } } } } } },
      _count: { select: { banners: true } },
    },
  });
  return media.map((m) => ({
    id: m.id, publicPath: m.publicPath, storageKey: m.storageKey, sha256: m.sha256, mime: m.mime, bytes: m.bytes, width: m.width, height: m.height, origin: m.origin,
    alts: m.translations,
    usages: m.products.map((u) => {
      const ordered = [...u.product.media].sort((a, b) => Number(b.isPrimary) - Number(a.isPrimary) || a.sortOrder - b.sortOrder);
      return { productId: u.product.id, productRef: (u.product.sourceKey ?? u.product.id).split(":").pop()!, productTitle: u.product.translations[0]?.title ?? "", public: u.product.status === "PUBLISHED" && !u.product.needsReview, isMain: ordered[0]?.mediaId === m.id };
    }),
    bannerCount: m._count.banners,
  }));
}
