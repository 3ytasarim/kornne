import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { join, resolve, sep } from "node:path";
import type { Locale, PrismaClient } from "@prisma/client";
import { z } from "zod";
import { AdminError } from "./action-state";
import { slugify } from "./products";
import { LOCALES } from "@/lib/i18n/config";

/**
 * Media library (Sprint 6). The 445 imported originals are NEVER modified, moved or deleted: this module only edits
 * their metadata (alt / caption per language) and their product links. New uploads:
 *  - type from the file CONTENT (magic bytes), never from the extension or the browser's MIME claim
 *  - images must decode (sharp) and match the sniffed format; SVG is refused (script risk)
 *  - size / pixel limits, safe generated file name (no user path), write with "wx" (never overwrite)
 *  - identical content (SHA-256) is not stored twice — the existing asset is reused
 * Storage = the same flat media directory that serves /upload/<name> (MEDIA_DIR, docs/architecture/media-storage.md).
 */
export const IMAGE_MAX_BYTES = 10 * 1024 * 1024;
export const PDF_MAX_BYTES = 20 * 1024 * 1024;
const MAX_PIXELS = 40_000_000;

export type Sniffed = { mime: "image/jpeg" | "image/png" | "image/webp" | "image/gif" | "application/pdf"; ext: string };

/** Detects the real file type from its first bytes. Returns null for anything not on the allow-list. */
export function sniffType(buf: Uint8Array): Sniffed | null {
  const b = (i: number) => buf[i] ?? -1;
  const ascii = (from: number, len: number) => String.fromCharCode(...Array.from(buf.subarray(from, from + len)));
  if (b(0) === 0xff && b(1) === 0xd8 && b(2) === 0xff) return { mime: "image/jpeg", ext: "jpg" };
  if ([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a].every((x, i) => b(i) === x)) return { mime: "image/png", ext: "png" };
  if (ascii(0, 4) === "RIFF" && ascii(8, 4) === "WEBP") return { mime: "image/webp", ext: "webp" };
  if (ascii(0, 6) === "GIF87a" || ascii(0, 6) === "GIF89a") return { mime: "image/gif", ext: "gif" };
  if (ascii(0, 5) === "%PDF-") return { mime: "application/pdf", ext: "pdf" };
  return null;
}

/** "Döş Açma (1).JPG" → "kornne-dos-acma-1-<hash8>.jpg" — no user-controlled path segments at all. */
export function safeFileName(original: string, sha: string, ext: string): string {
  const base = slugify(original.replace(/\.[^.]*$/, "")).slice(0, 60) || "dosya";
  return `kornne-${base}-${sha.slice(0, 10)}.${ext}`;
}

function mediaDir() {
  return resolve(process.env.MEDIA_DIR ?? join(process.cwd(), "public", "upload"));
}

async function writeNew(name: string, buf: Buffer) {
  const root = mediaDir();
  const file = resolve(root, name);
  if (!file.startsWith(root + sep)) throw new AdminError("Geçersiz dosya adı.");
  try {
    await writeFile(file, buf, { flag: "wx" });
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code !== "EEXIST") throw e;
  }
}

const altSchema = z.string().trim().min(3, "Alt metin en az 3 karakter olmalı ve görseli anlatmalı.").max(160, "Alt metin en fazla 160 karakter.");

export async function uploadImage(db: PrismaClient, actor: { id: string }, file: File, alt: string) {
  const altText = altSchema.parse(alt);
  if (file.size === 0) throw new AdminError("Dosya boş.");
  if (file.size > IMAGE_MAX_BYTES) throw new AdminError("Görsel en fazla 10 MB olabilir.");
  const buf = Buffer.from(await file.arrayBuffer());
  const type = sniffType(buf);
  if (!type || type.mime === "application/pdf") throw new AdminError("Yalnız JPEG, PNG, WebP veya GIF görsel yüklenebilir (dosya içeriği kontrol edildi).");
  const { default: sharp } = await import("sharp");
  let meta: { format?: string; width?: number; height?: number };
  try {
    meta = await sharp(buf, { limitInputPixels: MAX_PIXELS }).metadata();
  } catch {
    throw new AdminError("Görsel çözümlenemedi (bozuk veya desteklenmeyen dosya).");
  }
  const fmt = meta.format === "jpg" ? "jpeg" : meta.format;
  if (`image/${fmt}` !== type.mime || !meta.width || !meta.height) throw new AdminError("Dosya içeriği uzantısıyla/biçimiyle uyuşmuyor.");
  const sha = createHash("sha256").update(buf).digest("hex");
  const existing = await db.mediaAsset.findFirst({ where: { sha256: sha } });
  if (existing) return { asset: existing, duplicate: true };
  const name = safeFileName(file.name, sha, type.ext);
  await writeNew(name, buf);
  const asset = await db.$transaction(async (tx) => {
    const a = await tx.mediaAsset.create({ data: { storageKey: `admin/${name}`, publicPath: `/upload/${name}`, sha256: sha, mime: type.mime, bytes: buf.length, width: meta.width, height: meta.height, origin: "admin_upload", uploadedById: actor.id, translations: { create: { locale: "tr", alt: altText, autoGenerated: false } } } });
    await tx.auditLog.create({ data: { actorId: actor.id, action: "media.uploaded", entityType: "MediaAsset", entityId: a.id, after: { publicPath: a.publicPath, mime: a.mime, bytes: a.bytes, sha256: sha } } });
    return a;
  });
  return { asset, duplicate: false };
}

export async function uploadDocument(db: PrismaClient, actor: { id: string }, productId: string, file: File, title: string, locale: Locale | null) {
  const t = z.string().trim().min(3, "Doküman başlığı girin.").max(160).parse(title);
  if (file.size === 0) throw new AdminError("Dosya boş.");
  if (file.size > PDF_MAX_BYTES) throw new AdminError("PDF en fazla 20 MB olabilir.");
  const buf = Buffer.from(await file.arrayBuffer());
  if (sniffType(buf)?.mime !== "application/pdf") throw new AdminError("Yalnız PDF yüklenebilir (dosya içeriği kontrol edildi).");
  const product = await db.product.findUnique({ where: { id: productId }, select: { id: true } });
  if (!product) throw new AdminError("Ürün bulunamadı.");
  const sha = createHash("sha256").update(buf).digest("hex");
  const name = safeFileName(file.name, sha, "pdf");
  const dup = await db.productDocument.findFirst({ where: { productId, sha256: sha } });
  if (dup) throw new AdminError("Bu doküman bu ürüne zaten eklenmiş.");
  await writeNew(name, buf);
  const count = await db.productDocument.count({ where: { productId } });
  const doc = await db.productDocument.create({ data: { productId, locale, title: t, storageKey: `admin/${name}`, publicPath: `/upload/${name}`, sha256: sha, mime: "application/pdf", bytes: buf.length, status: "UNVERIFIED", sortOrder: count, createdById: actor.id } });
  await db.auditLog.create({ data: { actorId: actor.id, action: "document.uploaded", entityType: "Product", entityId: productId, after: { documentId: doc.id, title: t, bytes: doc.bytes, sha256: sha } } });
  return doc;
}

export async function saveMediaText(db: PrismaClient, actor: { id: string }, raw: unknown) {
  const v = z.object({ mediaId: z.string().min(10).max(40), locale: z.enum(LOCALES), alt: altSchema, caption: z.string().trim().max(300).optional() }).parse(raw);
  const before = await db.mediaTranslation.findUnique({ where: { mediaId_locale: { mediaId: v.mediaId, locale: v.locale } } });
  const row = before
    ? await db.mediaTranslation.update({ where: { id: before.id }, data: { alt: v.alt, caption: v.caption || null, autoGenerated: false } })
    : await db.mediaTranslation.create({ data: { mediaId: v.mediaId, locale: v.locale, alt: v.alt, caption: v.caption || null, autoGenerated: false } });
  await db.auditLog.create({ data: { actorId: actor.id, action: "media.text_saved", entityType: "MediaAsset", entityId: v.mediaId, before: before ? { locale: before.locale, alt: before.alt, caption: before.caption } : undefined, after: { locale: v.locale, alt: row.alt, caption: row.caption } } });
  return row;
}

/** Product ↔ media links: order, primary image, attach / detach. The media file itself is never touched. */
export async function saveProductMedia(db: PrismaClient, actor: { id: string }, raw: unknown) {
  const v = z.object({ productId: z.string().min(10).max(40), order: z.array(z.string().min(10).max(40)).max(60), primaryId: z.string().optional(), attach: z.string().max(40).optional() }).parse(raw);
  return db.$transaction(async (tx) => {
    const links = await tx.productMedia.findMany({ where: { productId: v.productId } });
    const linked = new Set(links.map((l) => l.mediaId));
    const order = v.order.filter((id) => linked.has(id));
    const detach = links.filter((l) => !order.includes(l.mediaId)).map((l) => l.mediaId);
    if (v.attach && !linked.has(v.attach)) {
      const exists = await tx.mediaAsset.findUnique({ where: { id: v.attach }, select: { id: true } });
      if (!exists) throw new AdminError("Görsel bulunamadı.");
      order.push(v.attach);
      await tx.productMedia.create({ data: { productId: v.productId, mediaId: v.attach, sortOrder: order.length - 1 } });
    }
    if (detach.length) await tx.productMedia.deleteMany({ where: { productId: v.productId, mediaId: { in: detach } } });
    const primary = v.primaryId && order.includes(v.primaryId) ? v.primaryId : order[0];
    for (const [i, mediaId] of order.entries()) await tx.productMedia.update({ where: { productId_mediaId: { productId: v.productId, mediaId } }, data: { sortOrder: mediaId === primary ? -1 : i, isPrimary: mediaId === primary } });
    await tx.product.update({ where: { id: v.productId }, data: { updatedAt: new Date() } });
    await tx.auditLog.create({ data: { actorId: actor.id, action: "product.media_updated", entityType: "Product", entityId: v.productId, before: { order: links.sort((a, b) => a.sortOrder - b.sortOrder).map((l) => l.mediaId) }, after: { order, primary, detached: detach, attached: v.attach ?? null } } });
  });
}
