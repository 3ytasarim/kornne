import Link from "next/link";
import { AlertTriangle, ArrowRight } from "lucide-react";
import { ALL_NAV_ITEMS } from "@/components/admin/adminNav";
import { PageHeader, StatCard } from "@/components/admin/PageHeader";
import { Card } from "@/components/admin/ui";
import { Badge } from "@/components/ui/Badge";
import { DataTable } from "@/components/ui/DataTable";
import { Notice } from "@/components/ui/States";
import { fmtDateTime, istanbulDayStart } from "@/lib/admin/format";
import { LOW_CONFIDENCE } from "@/lib/admin/translations";
import { requireAdmin } from "@/lib/auth/guard";
import { can } from "@/lib/auth/rbac";
import { commerceGate } from "@/lib/commerce/gate";
import { requireDb } from "@/lib/db";
import { STATUS_LABEL, STATUS_TONE } from "@/lib/quote/status-labels";

export const metadata = { title: "Panel" };

/** Dashboard: every number is a live database count (no estimates, no revenue while paid checkout is closed). */
export default async function AdminDashboard({ searchParams }: PageProps<"/admin">) {
  const user = await requireAdmin("dashboard");
  const denied = (await searchParams).denied === "1";
  const db = requireDb();
  const today = istanbulDayStart();
  const showQuotes = can(user.role, "quotes");
  const showCatalog = can(user.role, "products") || can(user.role, "pricing");
  const [visibleCount, productStats, held, prices, legacyPrices, conflictRows, broken, autoAlt, matches, lowPending, quoteStats, todayQuotes, overdue, latestQuotes, orders, pagesReview, auditToday] = await Promise.all([
    db.product.count({ where: { status: "PUBLISHED", needsReview: false } }),
    db.product.groupBy({ by: ["status"], _count: true }),
    db.product.findMany({ where: { needsReview: true }, select: { id: true, sourceKey: true, translations: { where: { locale: "tr" }, select: { title: true } } } }),
    db.price.groupBy({ by: ["status", "source"], _count: true }),
    db.price.findMany({ where: { source: "LEGACY_IMPORT" }, select: { amountMinor: true, compareAtMinor: true } }),
    db.legacyMatchSuggestion.findMany({ where: { evidence: { path: ["priceEqual"], equals: false } }, select: { productId: true } }),
    db.legacySourceRecord.count({ where: { entityType: "media", migrationStatus: "missing_at_source" } }),
    db.mediaTranslation.count({ where: { autoGenerated: true } }),
    db.legacyMatchSuggestion.groupBy({ by: ["status"], _count: true }),
    db.legacyMatchSuggestion.count({ where: { status: "SUGGESTED", confidence: { lt: LOW_CONFIDENCE } } }),
    showQuotes ? db.quoteRequest.groupBy({ by: ["status"], where: { isTest: false }, _count: true }) : Promise.resolve([]),
    showQuotes ? db.quoteRequest.count({ where: { isTest: false, createdAt: { gte: today } } }) : Promise.resolve(0),
    showQuotes ? db.quoteRequest.count({ where: { isTest: false, followUpAt: { lt: new Date() }, status: { in: ["NEW", "IN_REVIEW", "QUOTE_PREPARED", "RESPONDED"] } } }) : Promise.resolve(0),
    showQuotes ? db.quoteRequest.findMany({ where: { isTest: false, status: { in: ["NEW", "IN_REVIEW", "QUOTE_PREPARED"] } }, orderBy: { createdAt: "desc" }, take: 6, select: { id: true, reference: true, status: true, createdAt: true, assignedTo: { select: { name: true } }, _count: { select: { items: true } } } }) : Promise.resolve([]),
    db.order.count({ where: { isTest: false } }),
    db.pageTranslation.count({ where: { state: "REVIEW" } }),
    db.auditLog.count({ where: { createdAt: { gte: today } } }),
  ]);
  const pc = (s: string) => productStats.find((x) => x.status === s)?._count ?? 0;
  const totalProducts = productStats.reduce((a, x) => a + x._count, 0);
  const verified = prices.filter((x) => x.status === "VERIFIED").reduce((a, x) => a + x._count, 0);
  const pendingPrices = prices.filter((x) => x.status === "UNVERIFIED" && x.source === "ADMIN").reduce((a, x) => a + x._count, 0);
  const invalidDiscounts = legacyPrices.filter((x) => x.compareAtMinor !== null && x.compareAtMinor <= x.amountMinor).length;
  const conflicts = new Set(conflictRows.map((c) => c.productId)).size;
  const mc = (s: string) => matches.find((x) => x.status === s)?._count ?? 0;
  const qc = (s: string) => (quoteStats as { status: string; _count: number }[]).find((x) => x.status === s)?._count ?? 0;
  const gate = commerceGate();

  const issues = [
    held.length ? { text: `${held.length} ürün incelemede bekletiliyor (${held.map((h) => `#${h.sourceKey?.split(":").pop()}`).join(", ")})`, href: "/admin/products?durum=inceleme" } : null,
    verified === 0 ? { text: `${legacyPrices.length} ham fiyatın hiçbiri onaylı değil — vitrinde “Fiyat için teklif alın”`, href: "/admin/pricing" } : null,
    conflicts ? { text: `${conflicts} üründe dil-fiyat çelişkisi`, href: "/admin/pricing?filtre=celiski" } : null,
    invalidDiscounts ? { text: `${invalidDiscounts} hatalı indirim (eski fiyat ≤ satış)`, href: "/admin/pricing?filtre=indirim" } : null,
    broken ? { text: `${broken} görsel kaynakta kırık (onarılmadı, 404)`, href: "/admin/media" } : null,
    mc("SUGGESTED") ? { text: `${mc("SUGGESTED")} EN/FR eşleşme önerisi karar bekliyor (${lowPending} düşük güvenli)`, href: "/admin/translations/matches" } : null,
    autoAlt ? { text: `${autoAlt} otomatik alt metin editör incelemesi bekliyor`, href: "/admin/media?alt=otomatik" } : null,
    pagesReview ? { text: `${pagesReview} içerik yayın onayı bekliyor`, href: "/admin/content?durum=REVIEW" } : null,
  ].filter((x): x is { text: string; href: string } => !!x);

  return (
    <>
      <PageHeader title={`Hoş geldiniz, ${user.name}`} description={`Canlı veritabanı özeti · ${fmtDateTime(new Date())} (İstanbul)`} />
      {denied ? (
        <Notice tone="warning" className="mb-6">
          Bu modüle erişim yetkiniz yok.
        </Notice>
      ) : null}

      {showQuotes ? (
        <section aria-labelledby="dash-quotes" className="mb-8">
          <h2 id="dash-quotes" className="mb-3 text-sm font-semibold text-steel">
            Teklifler
          </h2>
          <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-5">
            <StatCard label="Bugün gelen" value={todayQuotes} />
            <StatCard label="Yeni" value={qc("NEW")} tone={qc("NEW") ? "warning" : "neutral"} />
            <StatCard label="İşlemde" value={qc("IN_REVIEW") + qc("QUOTE_PREPARED")} />
            <StatCard label="Takibi geçmiş" value={overdue} tone={overdue ? "warning" : "neutral"} />
            <StatCard label="Sipariş" value={orders} hint={gate.enabled ? "" : "Online satış kapalı — ciro yok"} />
          </div>
        </section>
      ) : null}

      {showCatalog ? (
        <section aria-labelledby="dash-catalog" className="mb-8">
          <h2 id="dash-catalog" className="mb-3 text-sm font-semibold text-steel">
            Katalog
          </h2>
          <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-6">
            <StatCard label="Ürün" value={totalProducts} />
            <StatCard label="Yayında" value={visibleCount} tone="success" hint="vitrinde görünen" />
            <StatCard label="Taslak / arşiv" value={`${pc("DRAFT")} / ${pc("ARCHIVED")}`} />
            <StatCard label="Onaylı fiyat" value={`${verified} / ${legacyPrices.length}`} tone={verified ? "success" : "warning"} />
            <StatCard label="Bekleyen fiyat önerisi" value={pendingPrices} />
            <StatCard label="Eşleşme (bekleyen/onay/ret)" value={`${mc("SUGGESTED")}/${mc("APPROVED")}/${mc("REJECTED")}`} />
          </div>
        </section>
      ) : null}

      <div className="grid gap-6 xl:grid-cols-2">
        <Card title="Veri kalitesi ve bekleyen kararlar" description="Doğrudan ilgili yönetim ekranına gider.">
          {issues.length === 0 ? <p className="text-sm text-success">Açık konu yok.</p> : null}
          <ul className="space-y-2">
            {issues.map((i) => (
              <li key={i.href + i.text}>
                <Link href={i.href} className="group flex items-start gap-3 rounded-[var(--radius-md)] border border-line p-3 text-sm hover:border-brand-600">
                  <AlertTriangle aria-hidden="true" className="mt-0.5 size-4 shrink-0 text-warning" />
                  <span className="flex-1 text-ink">{i.text}</span>
                  <ArrowRight aria-hidden="true" className="size-4 text-brand-600 transition-transform group-hover:translate-x-1" />
                </Link>
              </li>
            ))}
          </ul>
        </Card>
        {showQuotes ? (
          <Card title="Açık teklifler" actions={<Link href="/admin/quotes?durum=acik" className="text-sm font-semibold text-brand-700 hover:underline dark:text-brand-300">Tümü →</Link>}>
            <DataTable
              caption="Açık teklifler"
              rows={latestQuotes as { id: string; reference: string; status: string; createdAt: Date; assignedTo: { name: string } | null; _count: { items: number } }[]}
              rowKey={(r) => r.id}
              empty="Açık teklif yok."
              columns={[
                { key: "r", header: "Referans", cell: (r) => <Link href={`/admin/quotes/${r.id}`} className="font-mono text-brand-700 hover:underline dark:text-brand-300">{r.reference}</Link> },
                { key: "s", header: "Durum", cell: (r) => <Badge tone={STATUS_TONE[r.status]}>{STATUS_LABEL[r.status]}</Badge> },
                { key: "a", header: "Sorumlu", cell: (r) => r.assignedTo?.name ?? "—" },
                { key: "d", header: "Tarih", cell: (r) => fmtDateTime(r.createdAt) },
              ]}
            />
          </Card>
        ) : (
          <Card title="Modüller">
            <ul className="grid gap-2 sm:grid-cols-2">
              {ALL_NAV_ITEMS.filter((m) => m.module !== "dashboard" && can(user.role, m.module)).map((m) => (
                <li key={m.href}>
                  <Link href={m.href} className="flex min-h-11 items-center justify-between rounded-[var(--radius-md)] border border-line px-3 text-sm font-medium hover:border-brand-600">
                    {m.label} <ArrowRight aria-hidden="true" className="size-4 text-brand-600" />
                  </Link>
                </li>
              ))}
            </ul>
          </Card>
        )}
      </div>
      <p className="mt-6 text-xs text-steel">Bugünkü yönetim işlemi: {auditToday} · Online satış kapısı: {gate.enabled ? "açık" : `kapalı (${gate.blockers.length} ön koşul eksik)`}</p>
    </>
  );
}
