import Image from "next/image";
import Link from "next/link";
import type { Prisma } from "@prisma/client";
import { ActionForm, FormMessage, Input, SubmitButton } from "@/components/admin/forms";
import { PageHeader, StatCard } from "@/components/admin/PageHeader";
import { Card, FilterBar, FilterSearch, FilterSelect, ModuleState, Pagination } from "@/components/admin/ui";
import { Badge } from "@/components/ui/Badge";
import { DataTable } from "@/components/ui/DataTable";
import { pageParam, strParam } from "@/lib/admin/format";
import { requireAdmin } from "@/lib/auth/guard";
import { allowed } from "@/lib/auth/rbac";
import { requireDb } from "@/lib/db";
import { uploadProductImageAction } from "../products/actions";

export const metadata = { title: "Medya" };
const PER_PAGE = 48;
const src = (p: string) => `/upload/${p.replace(/^\/upload\//, "").split("/").map(encodeURIComponent).join("/")}`;

/**
 * Media library. The 445 imported originals are listed read-only as files (never modified / moved / deleted);
 * editors manage alt texts, captions and product links. Source-broken legacy URLs are reported, not "repaired".
 */
export default async function MediaPage({ searchParams }: PageProps<"/admin/media">) {
  const user = await requireAdmin("media");
  const sp = await searchParams;
  const q = strParam(sp.q);
  const use = strParam(sp.kullanim);
  const alt = strParam(sp.alt);
  const origin = strParam(sp.kaynak);
  const page = pageParam(sp.sayfa);
  const db = requireDb();
  const where: Prisma.MediaAssetWhereInput = {};
  if (q) where.OR = [{ publicPath: { contains: q, mode: "insensitive" } }, { translations: { some: { alt: { contains: q, mode: "insensitive" } } } }];
  if (use === "kullanilan") where.products = { some: {} };
  if (use === "kullanilmayan") where.products = { none: {} };
  if (alt === "otomatik") where.translations = { some: { locale: "tr", autoGenerated: true } };
  if (alt === "eksik") where.translations = { none: { locale: "tr" } };
  if (alt === "duzenlenmis") where.translations = { some: { locale: "tr", autoGenerated: false } };
  if (origin === "legacy_import" || origin === "admin_upload") where.origin = origin;
  const [items, total, all, used, auto, broken, small] = await Promise.all([
    db.mediaAsset.findMany({ where, orderBy: { publicPath: "asc" }, skip: (page - 1) * PER_PAGE, take: PER_PAGE, include: { translations: { where: { locale: "tr" } }, _count: { select: { products: true } } } }),
    db.mediaAsset.count({ where }),
    db.mediaAsset.count(),
    db.mediaAsset.count({ where: { products: { some: {} } } }),
    db.mediaTranslation.count({ where: { locale: "tr", autoGenerated: true } }),
    db.legacySourceRecord.findMany({ where: { entityType: "media", migrationStatus: "missing_at_source" }, select: { legacyId: true, sourceUrl: true, payload: true } }),
    db.mediaAsset.count({ where: { products: { some: { isPrimary: true } }, OR: [{ width: { lt: 500 } }, { height: { lt: 500 } }] } }),
  ]);
  const pages = Math.max(1, Math.ceil(total / PER_PAGE));
  const params = new URLSearchParams(Object.entries({ q, kullanim: use, alt, kaynak: origin }).filter(([, v]) => v));
  return (
    <>
      <PageHeader title="Medya kütüphanesi" description="Orijinal dosyalar değiştirilmez; eski /upload adresleri korunur. Alt metin, açıklama ve ürün bağlantıları yönetilir." actions={<ModuleState state="live" />} />
      <div className="mb-6 grid gap-4 sm:grid-cols-2 xl:grid-cols-5">
        <StatCard label="Toplam dosya" value={all} hint="445 eski site orijinali + yüklenenler" />
        <StatCard label="Ürüne bağlı" value={used} />
        <StatCard label="Otomatik alt metin" value={auto} tone={auto ? "warning" : "success"} hint="Editör incelemesi bekliyor" />
        <StatCard label="Kaynakta kırık" value={broken.length} tone="warning" hint="Onarılmadı; 404 döner" />
        <StatCard label="Küçük ana görsel" value={small} tone={small ? "warning" : "neutral"} hint="500 px altı (Merchant için)" />
      </div>
      {allowed(user.role, "media.upload") ? (
        <Card title="Görsel yükle" className="mb-6" description="JPEG/PNG/WebP/GIF · en fazla 10 MB · dosya içeriği doğrulanır · SVG kabul edilmez.">
          <ActionForm action={uploadProductImageAction} className="grid gap-4 md:grid-cols-[1fr_1fr_auto] md:items-end" aria-label="Görsel yükle" resetOnOk>
            <label className="flex min-w-0 flex-col gap-1.5 text-sm font-semibold text-ink">
              Dosya
              <input type="file" name="file" accept="image/jpeg,image/png,image/webp,image/gif" required className="w-full min-w-0 min-h-12 rounded-[var(--radius-md)] border border-line-strong bg-surface p-2 text-sm font-normal" />
            </label>
            <Input name="alt" label="Alt metin (Türkçe)" required />
            <SubmitButton pendingText="Yükleniyor…">Yükle</SubmitButton>
            <FormMessage className="md:col-span-3" />
          </ActionForm>
        </Card>
      ) : null}
      <FilterBar action="/admin/media" resetHref="/admin/media" label="Medya filtreleri">
        <FilterSearch value={q} placeholder="Dosya adı veya alt metin" />
        <FilterSelect name="kullanim" label="Kullanım" value={use} options={[["", "Tümü"], ["kullanilan", "Ürüne bağlı"], ["kullanilmayan", "Bağlı değil"]]} />
        <FilterSelect name="alt" label="Alt metin (TR)" value={alt} options={[["", "Tümü"], ["otomatik", "Otomatik taslak"], ["duzenlenmis", "Editör onaylı"], ["eksik", "Yok"]]} />
        <FilterSelect name="kaynak" label="Kaynak" value={origin} options={[["", "Tümü"], ["legacy_import", "Eski site orijinali"], ["admin_upload", "Panelden yüklenen"]]} />
      </FilterBar>
      <ul className="grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-4 2xl:grid-cols-6">
        {items.map((m) => (
          <li key={m.id}>
            <Link href={`/admin/media/${m.id}`} className="group block overflow-hidden rounded-[var(--radius-md)] border border-line bg-surface hover:border-brand-600">
              <div className="relative aspect-square bg-surface-2">
                <Image src={src(m.publicPath)} alt="" fill sizes="(min-width: 1536px) 16vw, (min-width: 1024px) 25vw, 50vw" className="object-contain p-2" />
              </div>
              <div className="space-y-1 p-2.5 text-xs">
                <p className="line-clamp-2 font-medium text-ink">{m.translations[0]?.alt ?? <span className="text-warning">Alt metin yok</span>}</p>
                <p className="flex flex-wrap gap-1">
                  {m.translations[0]?.autoGenerated ? <Badge tone="warning">Otomatik</Badge> : null}
                  <Badge tone="outline">{m._count.products} ürün</Badge>
                  {m.origin === "admin_upload" ? <Badge tone="brand">Yüklendi</Badge> : null}
                </p>
              </div>
            </Link>
          </li>
        ))}
      </ul>
      <Pagination page={Math.min(page, pages)} pages={pages} total={total} href={(p) => `/admin/media?${new URLSearchParams([...params, ...(p > 1 ? [["sayfa", String(p)]] : [])])}`} />
      <Card title="Kaynakta kırık görseller" className="mt-8" description="Eski sitede de açılmıyordu. Yeni sitede sahte görselle 'onarılmadı'; eski URL 404 döner. Orijinaller müşteriden istenecek.">
        <DataTable
          caption="Kırık görseller"
          rows={broken}
          rowKey={(b) => b.legacyId}
          empty="Yok"
          columns={[
            { key: "u", header: "Eski URL", cell: (b) => <code className="text-xs break-all">{b.sourceUrl}</code> },
            { key: "h", header: "Kaynak HTTP", cell: (b) => (b.payload as { http_status?: string }).http_status ?? "—" },
            { key: "k", header: "Kullanıldığı yer", cell: (b) => <span className="text-xs">{(b.payload as { usages?: string }).usages ?? "—"}</span> },
          ]}
        />
      </Card>
    </>
  );
}
