import Image from "next/image";
import Link from "next/link";
import { notFound } from "next/navigation";
import { ActionForm, Area, FormMessage, Input, SubmitButton } from "@/components/admin/forms";
import { PageHeader } from "@/components/admin/PageHeader";
import { Card, KeyValues } from "@/components/admin/ui";
import { Badge } from "@/components/ui/Badge";
import { fmtDateTime } from "@/lib/admin/format";
import { requireAdmin } from "@/lib/auth/guard";
import { allowed } from "@/lib/auth/rbac";
import { requireDb } from "@/lib/db";
import { dirOf, LOCALE_META, LOCALES } from "@/lib/i18n/config";
import { saveMediaTextAction } from "../../products/actions";

export const metadata = { title: "Medya" };
const src = (p: string) => `/upload/${p.replace(/^\/upload\//, "").split("/").map(encodeURIComponent).join("/")}`;

export default async function MediaDetail({ params }: PageProps<"/admin/media/[id]">) {
  const user = await requireAdmin("media");
  const { id } = await params;
  const m = await requireDb().mediaAsset.findUnique({ where: { id }, include: { translations: true, products: { include: { product: { select: { id: true, translations: { where: { locale: "tr" }, select: { title: true } } } } } }, banners: { select: { id: true } } } });
  if (!m) notFound();
  const canEdit = allowed(user.role, "media.edit");
  return (
    <>
      <p className="mb-2 text-sm">
        <Link href="/admin/media" className="text-brand-700 hover:underline dark:text-brand-300">
          ← Medya kütüphanesi
        </Link>
      </p>
      <PageHeader title={m.publicPath.replace("/upload/", "")} description={m.origin === "legacy_import" ? "Eski site orijinali — dosya değiştirilemez, adresi korunur." : "Panelden yüklendi."} />
      <div className="grid gap-6 xl:grid-cols-[minmax(0,28rem)_1fr]">
        <div className="space-y-6">
          <Card>
            <div className="relative aspect-square overflow-hidden rounded-[var(--radius-md)] bg-surface-2">
              <Image src={src(m.publicPath)} alt={m.translations.find((t) => t.locale === "tr")?.alt ?? ""} fill sizes="448px" className="object-contain" />
            </div>
          </Card>
          <Card title="Dosya">
            <KeyValues
              rows={[
                ["Adres", <a key="a" href={src(m.publicPath)} target="_blank" rel="noopener" className="break-all text-brand-700 hover:underline dark:text-brand-300">{m.publicPath}</a>],
                ["Boyut", `${m.width ?? "?"}×${m.height ?? "?"} px · ${(m.bytes / 1024).toFixed(0)} KB`],
                ["Tür", m.mime],
                ["SHA-256", <code key="h" className="text-[11px] break-all">{m.sha256}</code>],
                ["Kayıt", fmtDateTime(m.createdAt)],
              ]}
            />
            {(m.width ?? 0) < 500 || (m.height ?? 0) < 500 ? <p className="mt-3 text-xs text-warning">500 px altında: ana ürün görseli olarak Google Merchant için yetersiz olabilir.</p> : null}
          </Card>
          <Card title="Kullanıldığı yerler">
            {m.products.length === 0 && m.banners.length === 0 ? <p className="text-sm text-steel">Bağlı ürün yok.</p> : null}
            <ul className="space-y-1 text-sm">
              {m.products.map((p) => (
                <li key={p.productId}>
                  <Link href={`/admin/products/${p.productId}?tab=gorseller`} className="text-brand-700 hover:underline dark:text-brand-300">
                    {p.product.translations[0]?.title}
                  </Link>{" "}
                  {p.isPrimary ? <Badge tone="brand">Ana görsel</Badge> : null}
                </li>
              ))}
              {m.banners.map((b) => (
                <li key={b.id}>Duyuru/banner</li>
              ))}
            </ul>
          </Card>
        </div>
        <Card title="Alt metin ve açıklama" description="Alt metin görselde gerçekten ne olduğunu anlatmalı; anahtar kelime yığını değil. Otomatik taslaklar editör onayı bekler.">
          <div className="space-y-5">
            {LOCALES.map((l) => {
              const t = m.translations.find((x) => x.locale === l);
              return (
                <ActionForm key={l} action={saveMediaTextAction} className="space-y-3 rounded-[var(--radius-md)] border border-line p-4" aria-label={`Alt metin ${l}`}>
                  <p className="flex items-center gap-2 text-sm font-semibold text-ink">
                    {LOCALE_META[l].nativeName} {t ? (t.autoGenerated ? <Badge tone="warning">Otomatik taslak</Badge> : <Badge tone="success">Editör</Badge>) : <Badge tone="outline">Yok</Badge>}
                  </p>
                  <input type="hidden" name="mediaId" value={m.id} />
                  <input type="hidden" name="locale" value={l} />
                  <div lang={l} dir={dirOf(l)} className="space-y-3">
                    <Input name="alt" label="Alt metin" defaultValue={t?.alt ?? ""} required />
                    <Area name="caption" label="Açıklama (isteğe bağlı)" defaultValue={t?.caption ?? ""} rows={2} />
                  </div>
                  {canEdit ? (
                    <div className="flex flex-wrap items-center gap-3">
                      <SubmitButton size="sm">Kaydet</SubmitButton>
                      <FormMessage />
                    </div>
                  ) : null}
                </ActionForm>
              );
            })}
          </div>
        </Card>
      </div>
    </>
  );
}
