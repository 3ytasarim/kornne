import { existsSync } from "node:fs";
import { join } from "node:path";
import Link from "next/link";
import { PageHeader, StatCard } from "@/components/admin/PageHeader";
import { SEO_NAV } from "@/components/admin/subnavs";
import { Card, FilterBar, FilterSelect, ModuleState, SubNav } from "@/components/admin/ui";
import { Badge } from "@/components/ui/Badge";
import { Notice } from "@/components/ui/States";
import { strParam } from "@/lib/admin/format";
import { requireAdmin } from "@/lib/auth/guard";
import { requireDb } from "@/lib/db";
import { geoSuggestions, siteGeoChecks, type GeoSuggestion } from "@/lib/seo/geo";

export const metadata = { title: "GEO önerileri" };
const PRIO = { high: ["Yüksek", "signal"], medium: ["Orta", "warning"], low: ["Düşük", "outline"] } as const;
const textOf = (html: string) => html.replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/\s+/g, " ").trim();

/**
 * Admin › SEO › GEO (Sprint 8): answer-engine readiness SUGGESTIONS from the real published texts. Nothing is
 * generated or written — no specs, claims, certificates or translations are invented; editors act in the editors.
 */
export default async function GeoPage({ searchParams }: PageProps<"/admin/seo/geo">) {
  await requireAdmin("seo");
  const prio = strParam((await searchParams).oncelik);
  const db = requireDb();
  const [products, faqSite, legal] = await Promise.all([
    db.product.findMany({
      where: { status: "PUBLISHED", needsReview: false },
      orderBy: { sortOrder: "asc" },
      select: { id: true, sourceKey: true, translations: { where: { locale: "tr" }, select: { title: true, descriptionHtml: true, seoDescription: true } }, specs: { where: { status: "VERIFIED" }, select: { id: true } }, faqItems: { where: { state: "PUBLISHED" }, select: { id: true } }, media: { select: { media: { select: { translations: { where: { locale: "tr" }, select: { autoGenerated: true } } } } } } },
    }),
    db.faqItem.count({ where: { state: "PUBLISHED", productId: null } }),
    db.siteSetting.findUnique({ where: { key: "company.legalName" }, select: { status: true } }),
  ]);
  const rows = products.map((p) => {
    const t = p.translations[0];
    const html = t?.descriptionHtml ?? "";
    const s = geoSuggestions({ title: t?.title ?? "", descriptionText: textOf(html), descriptionHtml: html, seoDescription: t?.seoDescription ?? null, verifiedSpecs: p.specs.length, faqCount: p.faqItems.length, images: p.media.length, imageAltsByEditor: p.media.filter((m) => m.media.translations.some((x) => !x.autoGenerated)).length });
    return { id: p.id, ref: (p.sourceKey ?? p.id).split(":").pop(), title: t?.title ?? p.id, suggestions: prio ? s.filter((x) => x.priority === prio) : s };
  });
  const site = siteGeoChecks({ hasLlmsTxt: existsSync(join(process.cwd(), "public", "llms.txt")), organizationVerified: legal?.status === "VERIFIED", faqPublished: faqSite, robotsAllowsAiBots: true });
  const count = (c: string) => rows.filter((r) => r.suggestions.some((s) => s.code === c)).length;

  return (
    <>
      <PageHeader title="GEO — yapay zekâ yanıt motorları için öneriler" description="ChatGPT, Gemini, Perplexity, Copilot gibi yanıt motorlarının içeriği doğru alıntılaması için öneriler. Bu ekran içerik ÜRETMEZ; yalnız mevcut yayımlanmış metne bakar ve kanıtıyla öneri verir." actions={<ModuleState state="live" title="Yalnız öneri" />} />
      <SubNav items={SEO_NAV} current="/admin/seo/geo" />
      <div className="mb-6 grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard label="Yapılandırılmamış teknik satırlar" value={count("unstructured-specs")} hint="doğrulanmış tablo yok" tone="warning" />
        <StatCard label="Şartname dili" value={count("tender-language")} />
        <StatCard label="Ürün SSS'si yok" value={count("no-faq")} />
        <StatCard label="Kısa açıklama" value={count("thin")} />
      </div>
      <Card className="mb-6" title="Site düzeyi">
        <SuggestionList items={site} />
      </Card>
      <Notice className="mb-6">Teknik değerler (güç, kapasite, ölçü), sertifika, garanti ve kullanım alanı müşteri teyidi olmadan yapılandırılmış veriye veya yeni metne dönüştürülmez. Öneriler editörün yapacağı işi tarif eder.</Notice>
      <FilterBar action="/admin/seo/geo" resetHref="/admin/seo/geo">
        <FilterSelect name="oncelik" label="Öncelik" value={prio} options={[["", "Tümü"], ["high", "Yüksek"], ["medium", "Orta"], ["low", "Düşük"]]} />
      </FilterBar>
      <div className="space-y-4">
        {rows.filter((r) => r.suggestions.length).map((r) => (
          <Card key={r.id} title={`#${r.ref} ${r.title}`} actions={<Link href={`/admin/products/${r.id}`} className="text-sm font-semibold text-brand-700 underline dark:text-brand-300">Ürünü düzenle</Link>}>
            <SuggestionList items={r.suggestions} />
          </Card>
        ))}
      </div>
    </>
  );
}

function SuggestionList({ items }: { items: GeoSuggestion[] }) {
  if (!items.length) return <p className="text-sm text-success">Öneri yok.</p>;
  return (
    <ul className="space-y-2 text-sm">
      {items.map((s) => {
        const [label, tone] = PRIO[s.priority];
        return (
          <li key={s.code}>
            <Badge tone={tone}>{label}</Badge> {s.message} <span className="block text-xs text-steel">Kanıt: {s.evidence}</span>
          </li>
        );
      })}
    </ul>
  );
}
