import "dotenv/config";
import { existsSync, rmSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { PrismaClient } from "@prisma/client";
import { PrismaPg } from "@prisma/adapter-pg";
import { testDatabaseUrl } from "../test-db-url.mjs";

/**
 * Safety net for e2e runs against the real development schema. Removes / reverts ONLY what test users (e-mail on the
 * reserved @kornne.test domain) or explicitly "E2E"-marked rows produced. Idempotent; called from afterEach of the
 * writing tests AND from global teardown (a test killed by its timeout never finishes its own `finally`).
 */
const db = () => new PrismaClient({ adapter: new PrismaPg({ connectionString: testDatabaseUrl("e2e") }), transactionOptions: { maxWait: 10_000, timeout: 30_000 } });

export async function cleanupE2eWrites() {
  const prisma = db();
  try {
    const testUsers = (await prisma.user.findMany({ where: { email: { endsWith: "@kornne.test" } }, select: { id: true } })).map((u) => u.id);

    // match decisions taken by test users → back to SUGGESTED, with everything the decision / publish created
    // decided by a test user — or by a user that no longer exists (a test user already removed by an earlier teardown)
    const allUsers = (await prisma.user.findMany({ select: { id: true } })).map((u) => u.id);
    const matches = await prisma.legacyMatchSuggestion.findMany({ where: { OR: [{ decidedById: { in: testUsers } }, { decidedById: { notIn: allUsers, not: null } }] } });
    for (const m of matches) {
      await prisma.$transaction(async (tx) => {
        const legacyRecordId = `product:${m.sourceLegacyId}:${m.sourceLocale}`;
        const t = await tx.productTranslation.findFirst({ where: { productId: m.productId, locale: m.sourceLocale, legacyRecordId } });
        if (t) await tx.productTranslation.delete({ where: { id: t.id } });
        const mids = (await tx.productMedia.findMany({ where: { productId: m.productId }, select: { mediaId: true } })).map((x) => x.mediaId);
        if (m.status === "APPROVED") await tx.mediaTranslation.deleteMany({ where: { mediaId: { in: mids }, locale: m.sourceLocale, autoGenerated: true } });
        const rec = await tx.legacySourceRecord.findUnique({ where: { entityType_legacyId_locale: { entityType: "product", legacyId: m.sourceLegacyId, locale: m.sourceLocale } } });
        if (rec) {
          await tx.legacySourceRecord.update({ where: { id: rec.id }, data: { targetId: null, migrationStatus: "match_suggested" } });
          const url = (rec.payload as { source_url?: string }).source_url;
          if (url && m.previousRedirectTo) await tx.redirect.updateMany({ where: { fromPath: decodeURIComponent(new URL(url).pathname), source: "LEGACY_AUDIT" }, data: { toPath: m.previousRedirectTo } });
        }
        const evidence = { ...(m.evidence as Record<string, unknown>) };
        const productId = typeof evidence.rematchedFrom === "string" ? evidence.rematchedFrom : m.productId;
        delete evidence.rematchedFrom;
        delete evidence.rematchedAt;
        await tx.legacyMatchSuggestion.update({ where: { id: m.id }, data: { status: "SUGGESTED", decidedById: null, decidedAt: null, note: null, previousRedirectTo: null, productId, evidence: evidence as object, ...(m.method === "manual_rematch" ? { method: "record-order+image-sha256+price" } : {}) } });
      });
    }

    // Sprint 8/9: SEO audit runs and Merchant dry-runs / mapping previews started by test users
    await prisma.seoAuditRun.deleteMany({ where: { OR: [{ createdById: { in: testUsers } }, { createdById: { notIn: allUsers, not: null } }] } });
    await prisma.merchantSyncRun.deleteMany({ where: { OR: [{ createdById: { in: testUsers } }, { createdById: { notIn: allUsers, not: null } }] } });

    // Sprint 12: EFT/Havale orders placed against the local copy are always isTest (KORNNE_TEST_DB=local-e2e); notices cascade
    await prisma.order.deleteMany({ where: { isTest: true, number: { startsWith: "TEST-" } } });
    await prisma.loginAttempt.deleteMany({ where: { OR: [{ key: { startsWith: "order:" } }, { key: { startsWith: "order-lookup:" } }, { key: { startsWith: "notice:" } }] } });

    // price proposals entered by test users (events cascade)
    await prisma.price.deleteMany({ where: { createdById: { in: testUsers } } });

    // images uploaded by test users: DB rows (+ product links / alt texts) and the stored files
    const uploads = await prisma.mediaAsset.findMany({ where: { origin: "admin_upload", uploadedById: { in: testUsers } }, select: { id: true, publicPath: true } });
    if (uploads.length) {
      await prisma.productMedia.deleteMany({ where: { mediaId: { in: uploads.map((u) => u.id) } } });
      await prisma.mediaAsset.deleteMany({ where: { id: { in: uploads.map((u) => u.id) } } });
      const root = resolve(process.env.MEDIA_DIR ?? join(process.cwd(), "public", "upload"));
      for (const u of uploads) {
        const file = resolve(root, basename(u.publicPath));
        if (file.startsWith(root) && existsSync(file)) rmSync(file);
      }
    }

    // CMS rows marked E2E
    await prisma.page.deleteMany({ where: { key: { startsWith: "e2e-" } } });
    await prisma.faqItem.deleteMany({ where: { question: { startsWith: "E2E" } } });
    await prisma.banner.deleteMany({ where: { translations: { some: { locale: "tr", title: { startsWith: "E2E" } } } } });
    await prisma.menuItem.deleteMany({ where: { labels: { path: ["tr"], string_starts_with: "E2E" } } });
    await prisma.redirect.deleteMany({ where: { source: "SLUG_CHANGE", OR: [{ fromPath: { contains: "e2e-" } }, { toPath: { contains: "e2e-" } }] } });

    // product SEO fields set by tests (originals are empty) and quote CRM side rows
    await prisma.productTranslation.updateMany({ where: { seoTitle: { startsWith: "E2E " } }, data: { seoTitle: null, seoDescription: null } });
    await prisma.notificationOutbox.deleteMany({ where: { entityType: "QuoteRequest", entityId: { notIn: (await prisma.quoteRequest.findMany({ select: { id: true } })).map((q) => q.id) } } });
  } finally {
    await prisma.$disconnect();
  }
}
